/** Grup legacy untuk komponen UI lama (dipakai sampai UI pindah ke v1, Fase 7). */
function legacyGroupOf(asset: Asset): DeviceGroup {
  if (asset.networkRole === "olt") return "OLT";
  return asset.vendor === "MikroTik" ? "MikroTik" : "Ruijie";
}

/** Proyeksi Asset → view-model legacy `NetworkDevice`. */
export function assetToLegacyDevice(asset: Asset): NetworkDevice {
  return {
    id: asset.assetId,
    name: asset.displayName,
    ip: asset.managementIp,
    group: legacyGroupOf(asset),
    area: asset.site,
    status: asset.status,
    latitude: asset.latitude ?? 0,
    longitude: asset.longitude ?? 0,
  };
}
